"""Audit every graded drill's course: python tools/ingame/audit.py [--write]

Follows the line the car actually drove in each drill's best recorded run (tests/fixtures/, gold first) and
reports, per drill: the physics surfaces under that line and its grip (surface.py, from inside the game: the
map must be loaded), the elevation it covers, the steepest 10 m grade and the most the car tilted. Use it to
spot venues where hills, camber or mixed surfaces muddy a drill's mechanics, and to re-check after a game update.
--write regenerates docs/COURSE_AUDIT.md.
"""
import argparse
import glob
import json
import math
import os
import re
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.stdout.reconfigure(encoding="utf-8")

import surface  # noqa: E402
from game import lua  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "tests" / "fixtures"
DOC = ROOT / "docs" / "COURSE_AUDIT.md"
RANK = {"gold": 0, "silver": 1, "bronze": 2}


def best_fixtures():
    """{drill: fixture path}: per drill, a gold run if there is one, else silver, bronze, then any."""
    best = {}
    for f in sorted(glob.glob(str(FIXTURES / "*.json"))):
        m = re.match(r"([a-e]\d\d)c?_(\w+)\.json$", os.path.basename(f))
        if not m:
            continue
        drill, tag = m.group(1).upper(), m.group(2)
        rank = min((r for t, r in RANK.items() if tag.startswith(t)), default=9)
        if drill not in best or rank < best[drill][0]:
            best[drill] = (rank, f)
    return {d: f for d, (_, f) in best.items()}


def course(path):
    """The driven line: samples from the run's start, with distance along it."""
    r = json.load(open(path, encoding="utf-8"))
    ss = [s for s in r.get("samples", []) if s.get("t", 0) >= r.get("runStartT", 0) and "x" in s]
    dist = [0.0]
    for a, b in zip(ss, ss[1:]):
        dist.append(dist[-1] + math.hypot(b["x"] - a["x"], b["y"] - a["y"]))
    return r, ss, dist


def terrain_numbers(ss, dist):
    z = [s.get("z", 0) for s in ss]
    grade, j = 0.0, 0
    for i in range(len(ss)):
        while j < len(ss) - 1 and dist[j] - dist[i] < 10:
            j += 1
        if dist[j] - dist[i] >= 9:
            grade = max(grade, abs(z[j] - z[i]) / (dist[j] - dist[i]) * 100)
    tilts = [math.degrees(math.acos(max(-1.0, min(1.0, s["uz"])))) for s in ss if "uz" in s]
    return {"lengthM": round(dist[-1]), "riseM": round(max(z) - min(z), 1), "gradePct": round(grade, 1),
            "tiltDeg": round(max(tilts), 1) if tilts else None}


def audit():
    level = str(lua("local l = getCurrentLevelIdentifier() return tostring(l)"))
    fric = surface.friction()
    rows = []
    for drill, path in sorted(best_fixtures().items()):
        rec, ss, dist = course(path)
        if len(ss) < 5:
            continue
        lvl = (rec.get("meta") or {}).get("level") or rec.get("level")
        if lvl and lvl != level:
            print(f"  {drill}: recorded on {lvl}, {level} is loaded; skipped")
            continue
        pts, nxt = [], 0.0
        for s, d in zip(ss, dist):
            if d >= nxt:
                pts.append((s["x"], s["y"], s.get("z", 0) - 0.4))
                nxt = d + 5
        surf = surface.summary(surface.counts(pts, radius=3.0), fric)
        row = {"drill": drill, "fixture": os.path.basename(path)[:-5], **terrain_numbers(ss, dist),
               "surface": surface.describe(surf), "mu": surf["mu"], "shares": surf["shares"],
               "obstacleTris": surf["obstacleTris"]}
        rows.append(row)
        print(f"  {drill:4} {row['lengthM']:4} m  rise {row['riseM']:5.1f} m  grade {row['gradePct']:5.1f} %  "
              f"tilt {row['tiltDeg'] if row['tiltDeg'] is not None else '-':>5}°  {row['surface']}", flush=True)
    return level, rows, fric


def flag(r):
    notes = []
    if r["gradePct"] > 12:
        notes.append("steep")
    elif r["gradePct"] > 8:
        notes.append("sloped")
    if (r["tiltDeg"] or 0) > 12:
        notes.append("tilted")
    top = next(iter(r["shares"].values()), 100)
    if top < 85:
        notes.append("mixed surface")
    return ", ".join(notes) or "flat, one surface"


def write_doc(level, rows, fric):
    version = lua("return tostring(beamng_versionb or beamng_version or '?')")
    lines = ["# Course audit", "",
             f"Generated by `python tools/ingame/audit.py --write` on {date.today()} ({level}, BeamNG {version}). "
             "Don't edit by hand.", "",
             "Each graded drill's course, along the line the car drove in its best recorded run: the physics "
             "surfaces under it and their grip (static friction), the height it covers, the steepest 10 m grade and the "
             "most the car tilted. Hills, camber and mixed surfaces blur a drill's mechanics, so flatter, single-surface "
             "venues isolate them better; D05, D06 and E05 are about the slope on purpose.", "",
             "| Drill | Run | Length | Rise | Grade | Tilt | Surface (grip) | Note |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| {r['drill']} | `{r['fixture']}` | {r['lengthM']} m | {r['riseM']} m | {r['gradePct']} % | "
                     f"{r['tiltDeg'] if r['tiltDeg'] is not None else '–'}° | {r['surface']} | {flag(r)} |")
    lines += ["", "## Surface grip", "",
              "Static and sliding friction of the ground models drills use, from `core_environment.groundModels` "
              "(the values BeamNG's Groundmodel Debug panel edits). Loose depth is the soft layer the tyres sink into.", "",
              "| Ground model | Static friction | Sliding friction | Roughness | Loose depth |", "| --- | --- | --- | --- | --- |"]
    for g in ("ASPHALT", "ASPHALT_WET", "COBBLESTONE", "ROCK", "GRAVEL", "GRAVEL_WET", "DIRT", "DIRT_DUSTY",
              "DIRT_DUSTY_LOOSE", "GRASS", "SAND", "MUD", "SNOW", "ICE"):
        if g in fric:
            f = fric[g]
            lines.append(f"| {g} | {f['mu']:.2f} | {f['slide']:.2f} | {f['rough']:.2f} | {f['depth']:.2f} m |")
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")


def main(argv):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--write", action="store_true", help="regenerate docs/COURSE_AUDIT.md")
    a = p.parse_args(argv)
    level, rows, fric = audit()
    if a.write:
        write_doc(level, rows, fric)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
